// CMM Tune Lab — self test.   Run:  node selftest.js
//
// Two jobs, and the second is the reason this file exists.
//
// 1. The page boots. A browser page with no build step dies silently on a single exception — the
//    markup still renders, so it looks fine while nothing works. The Dial Lab shipped in exactly
//    that state for a day before anyone noticed.
//
// 2. THE DSP STILL MATCHES THE C. The whole premise of this bench is that a number settled here is
//    the same number in the game. The previous bench used Web Audio biquads (12 dB/oct) where the
//    game uses one-poles (6 dB/oct), so five of its parameters could never have transferred and
//    nobody would have found out until after the port. Here the worklet is a transcription of
//    sfx_capture_static_tone + the SFX_KIND_STATIC branch of render_sfx_add, and this test diffs it
//    against samples generated by compiling that C. If someone "tidies" the JS, this goes red.
//
// The expected values below came from gcc -O0 on a verbatim copy of the C, seed 22222, 48 kHz,
// low 50 Hz / high 2100 Hz / crackle 0.8. Regenerate them the same way if the C ever changes.

const fs = require("fs");
const path = require("path");
const src = fs.readFileSync(path.join(__dirname, "index.html"), "utf8");
let failures = 0;
const fail = m => { failures++; console.log("  FAIL  " + m); };
const pass = m => console.log("  ok    " + m);

// ── 1. Wiring ─────────────────────────────────────────────────────────────────────────────────
console.log("\nWiring");
const js = /<script>([\s\S]*)<\/script>/.exec(src)[1];
const ids = new Set([...src.matchAll(/id="([^"]+)"/g)].map(m => m[1]));
const refs = new Set([...js.matchAll(/getElementById\("([^"]+)"\)/g)].map(m => m[1]));
const missing = [...refs].filter(r => !ids.has(r));
missing.length ? fail("referenced but not in the markup: " + missing.join(", "))
               : pass(`${refs.size} referenced elements all exist`);

// ── 2. C PARITY — the load-bearing check ──────────────────────────────────────────────────────
console.log("\nDSP parity with cmm_mix.c");
const EXPECTED = [
  [0, -0.065015502], [100, 0.017866379], [200, 0.141513348], [300, -0.112570919],
  [400, 0.159419954], [500, 0.215183839], [600, 0.200801551], [700, -0.088180549],
  [800, -0.182237819], [900, -0.017610034], [1000, 0.104832903], [1100, 0.054017693],
  [1200, -0.090094864], [1300, 0.083695315], [1400, 0.088557310], [1500, -0.109143004],
  [1600, -0.028908858], [1700, 0.016207000], [1800, -0.024682835], [1900, 0.076702051],
];
const worklet = /const WORKLET = `([\s\S]*?)`;/.exec(js)[1];
globalThis.AudioWorkletProcessor = class {
  constructor() { this.port = { postMessage() {}, onmessage: null }; }
};
globalThis.registerProcessor = (n, c) => { globalThis.__Proc = c; };
globalThis.sampleRate = 48000;
try {
  new Function(worklet)();
  pass("the worklet source parses and registers");
} catch (e) {
  fail("the worklet threw: " + e.message);
}
if (globalThis.__Proc) {
  const p = new globalThis.__Proc();
  p.p = { lowHz: 50, highHz: 2100, crackle: 0.8, staticVol: 1, outMs: 250, loadMs: 700,
          inMs: 250, holdMs: 2200, dull: 0, mono: 0, musicVol: 0, master: 1 };
  p.rng = 22222 >>> 0;
  p.running = true; p.once = false;
  p.t = 12000;                              // parked inside the gap: station silent, static open
  const N = 2000;
  const out = [[new Float32Array(N), new Float32Array(N)]];
  const inp = [[new Float32Array(N), new Float32Array(N)]];
  p.process(inp, out);
  let worst = 0, at = -1;
  for (const [i, want] of EXPECTED) {
    const d = Math.abs(out[0][0][i] - want);
    if (d > worst) { worst = d; at = i; }
  }
  // 1e-6 is generous for float32: the C stores float, JS computes in double and rounds on store.
  worst < 1e-6
    ? pass(`matches the C to ${worst.toExponential(2)} across ${EXPECTED.length} probes`)
    : fail(`DIVERGED from the C by ${worst.toExponential(3)} at sample ${at} — ` +
           "numbers settled in this bench will NOT transfer to the game");
}

// ── 3. Boot the page ──────────────────────────────────────────────────────────────────────────
console.log("\nBoot");
const store = {};
const el = id => ({
  id, value: "", textContent: "", tagName: "DIV", files: [], style: {}, _h: null,
  classList: { add() {}, remove() {}, toggle() {}, contains: () => false },
  addEventListener(ev, fn) { (this._h ||= {})[ev] = fn; },
  click() {}, append() {}, appendChild() {}, disabled: false,
  getBoundingClientRect: () => ({ width: 900, height: 118 }),
  getContext: () => new Proxy({}, { get: () => () => ({}) }),
  clientWidth: 900, clientHeight: 118, width: 900, height: 118,
});
Object.assign(globalThis, {
  AudioContext: function () { return {}; },
  document: {
    getElementById: id => (store[id] ||= el(id)),
    createElement: () => el("new"),
    addEventListener() {}, body: { appendChild() {} },
  },
  requestAnimationFrame: () => 0,
  addEventListener: () => {},
  getComputedStyle: () => ({ fontFamily: "monospace" }),
  URL: { createObjectURL: () => "blob:x", revokeObjectURL() {} },
  Blob: function () {},
  devicePixelRatio: 1,
});
globalThis.window = globalThis;
Object.defineProperty(globalThis, "navigator", {
  value: { clipboard: { writeText: async () => {} } }, configurable: true, writable: true,
});
try {
  new Function(js)();
  pass("script ran to completion, no exception");
} catch (e) {
  fail(`threw on load — ${e.constructor.name}: ${e.message}`);
  console.log("        " + (e.stack || "").split("\n")[1]);
}
const wired = Object.values(store).filter(v => v._h).length;
wired >= 8 ? pass(`${wired} elements have handlers attached`)
           : fail(`only ${wired} elements wired — setup stopped early`);
const exported = (store["export"] || {}).textContent || "";
exported.includes("<RadioStaticLowHz>")
  ? pass(`export panel generated ${exported.length} chars`)
  : fail("export panel is empty — updateExport never ran");

// Sliders must exist for every parameter, or it cannot be tuned.
const built = Object.keys(store).length;
console.log(`\n${failures ? failures + " FAILURE(S)" : "All checks passed."}  (${built} elements touched)\n`);
process.exit(failures ? 1 : 0);
